function p = bike_params()
% 자전거 진동 모델 기본값. 숫자를 바꿀 땐 여기 한 곳만 고치면 됨.
%
% 모델: 바퀴 하나당 2자유도 (자전거+바퀴 질량 m1, 사람 질량 m2)
%
%        [ 사람 m2 ]
%           |  kr, cr   (팔다리 = 스프링+댐퍼)
%        [ 자전거 m1 ]  ← 센서(ADXL345)가 붙은 곳
%           |  kt, ct   (타이어)
%     ~~~~ 노면 zr ~~~~
%
% 앞바퀴, 뒷바퀴를 각각 계산하고 (뒷바퀴는 축거 L/v 초 늦게 같은 노면을 지남)
% 센서 위치에 따라 wf : (1-wf) 비율로 섞는다.

% ----- 주행 -----
p.v = 5.0;           % 속도 (m/s). 5 m/s = 18 km/h

% ----- 자전거 + 사람 (한쪽 바퀴 몫) -----
p.m1 = 15.0;         % 자전거 프레임+바퀴 몫 (kg)
p.m2 = 37.5;         % 사람 몫 (kg) - 체중 75kg 의 절반
p.kt = 1.2e5;        % 타이어 강성 (N/m) - 공기압 높을수록 큼
p.ct = 150;          % 타이어 감쇠 (N·s/m)
p.kr = 2.5e4;        % 사람 팔다리 강성 (N/m)
p.cr = 900;          % 사람 팔다리 감쇠 (N·s/m)
p.L  = 1.05;         % 축거: 앞바퀴~뒷바퀴 거리 (m)
p.wf = 0.7;          % 센서가 앞바퀴 쪽 움직임을 얼마나 받는지 (0~1). 핸들/앞쪽이면 0.7 정도
p.contact = 0.08;    % 타이어 접지 길이 (m). 노면을 이 길이만큼 뭉개서 받아들임
p.R = 0.34;          % 바퀴 반지름 (m). 짧은 구멍엔 바퀴가 끝까지 안 빠지는 효과

% ----- 노면 거칠기 (ISO 8608) -----
% Gd = 기준 거칠기 (m^3). A등급(아주 좋음) 16e-6, B등급(보통 도로) 64e-6, C등급 256e-6
p.Gd   = 64e-6;
p.nmin = 0.05;       % 노면 파장 범위 (cycle/m)
p.nmax = 25;

% ----- 센서 (ADXL345, pothole_detect.py 설정과 같게) -----
p.fs_sim = 2000;     % 내부 계산 주기 (Hz)
p.fs     = 400;      % 센서 측정 주기 (Hz)  ← 0x2C = 0x0C
p.noise  = 0.01;     % 센서 잡음 (g)
p.lsb    = 0.0039;   % 분해능 (g)
p.range  = 16;       % 측정 범위 ±16g    ← 0x31 = 0x0B

% ----- 감지 방식 (calibrate.py / pothole_detect.py 와 같게) -----
p.window    = 0.05;  % 충격 점수 평균 시간 (s)   = WINDOW
p.cooldown  = 2.0;   % 감지 후 쉬는 시간 (s)     = COOLDOWN
p.threshold = 1.2;   % Simulink 감지기 기준값 (g) = THRESHOLD

% ----- 계산 방식 -----
p.use_simulink = true;   % true: Simulink 모델(bike_pothole_model.slx)로 계산
                         % false: 같은 식을 MATLAB 코드로 계산 (빠름, 3단계 반복 때 편함)
end
